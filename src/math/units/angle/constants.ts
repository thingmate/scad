/* turn <-> rad */

export const TURN_TO_RAD = Math.PI * 2;
export const RAD_TO_TURN = 1 / TURN_TO_RAD;

/* turn <-> deg */

export const TURN_TO_DEG = 360;
export const DEG_TO_TURN = 1 / TURN_TO_DEG;

/* deg <-> rad */

export const DEG_TO_RAD = Math.PI / 180;
export const RAD_TO_DEG = 1 / DEG_TO_RAD;
